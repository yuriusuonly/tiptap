/**
 * Android first-time-install onboarding: three placeholder pages introducing
 * the endless title + text paragraph feed. No animations — pages switch on
 * horizontal swipe, Next/Skip, and finishing persists `hasSeenOnboarding`
 * via the shared store.
 * @module src/android/screens/onboarding/onboarding-screen
 */
import {useRef, useState} from "react";
import {PanResponder, Pressable, Text, View} from "react-native";
import {APP_NAME} from "../../../shared/constants/configuration";
import {useOnboardingStore} from "../../../shared/store/onboarding-store";

const PAGES = [
  {
    eyebrow: `WELCOME TO ${APP_NAME.toUpperCase()}`,
    title: "Endless titles,\ntext paragraphs",
    body: "Scroll through an endless feed of AI-generated short titles and text paragraphs — something new on every card.",
  },
  {
    eyebrow: "READ FIRST",
    title: "Read something\nnew",
    body: "Each card pairs a short title with a bite-sized text paragraph, generated by AI and ready to read in seconds.",
  },
  {
    eyebrow: "START NOW",
    title: "Start\nyour feed",
    body: "Tap through below to begin. No video, no noise — just knowledge you can read.",
  },
];

export function OnboardingScreen() {
  const [page, setPage] = useState(0);
  const completeOnboarding = useOnboardingStore((state) => state.completeOnboarding);

  const isLastPage = page === PAGES.length - 1;
  const currentPage = PAGES[page];

  const goNext = () => {
    if (isLastPage) {
      completeOnboarding();
    } else {
      setPage((index) => index + 1);
    }
  };

  // Swipe handlers stay stable while reading the latest page via refs, so
  // the responder never captures a stale closure.
  const pageRef = useRef(page);
  pageRef.current = page;
  const completeRef = useRef(completeOnboarding);
  completeRef.current = completeOnboarding;

  const panResponder = useRef(
    PanResponder.create({
      onMoveShouldSetPanResponder: (_, gesture) =>
        Math.abs(gesture.dx) > 20 && Math.abs(gesture.dx) > Math.abs(gesture.dy),
      onPanResponderRelease: (_, gesture) => {
        const currentPageIndex = pageRef.current;
        if (gesture.dx < -50 && currentPageIndex < PAGES.length - 1) {
          setPage(currentPageIndex + 1);
        } else if (gesture.dx > 50 && currentPageIndex > 0) {
          setPage(currentPageIndex - 1);
        }
      },
    })
  ).current;

  return (
    <View
      {...panResponder.panHandlers}
      className="flex-1 items-center justify-center bg-background px-4 mobile:px-5 tablet:px-8 desktop:px-12"
    >
      <View className="w-full max-w-[480px] items-center mobile:max-w-[560px] tablet:max-w-[640px] desktop:max-w-[880px]">
        <View className="mb-6 flex-row items-center gap-2 rounded-full border border-line bg-surface px-3 py-1">
          <View className="h-1.5 w-1.5 rounded-full bg-accent" />
          <Text className="text-[11px] font-semibold leading-4 tracking-[1px] text-muted mobile:text-[12px] mobile:leading-[17px] mobile:tracking-[1.1px] tablet:text-[12px] tablet:leading-[18px] tablet:tracking-[1.2px] desktop:text-[13px] desktop:leading-[18px]">
            {currentPage.eyebrow}
          </Text>
        </View>

        <Text className="text-center text-[28px] font-extrabold leading-[34px] tracking-[-0.6px] text-ink mobile:text-[32px] mobile:leading-[38px] tablet:text-[36px] tablet:leading-[42px] desktop:text-[40px] desktop:leading-[48px]">
          {currentPage.title}
        </Text>

        <Text className="mt-4 text-center text-[14px] leading-5 text-muted mobile:text-[16px] mobile:leading-6 tablet:text-[18px] tablet:leading-[26px] desktop:text-[20px] desktop:leading-[30px]">
          {currentPage.body}
        </Text>

        <View className="mt-8 w-full items-center gap-2">
          <View className="h-2 w-3/4 rounded-full bg-raised" />
          <View className="h-2 w-2/3 rounded-full bg-raised" />
          <View className="h-2 w-1/2 rounded-full bg-raised" />
        </View>

        <View className="mt-10 flex-row items-center justify-between gap-4 self-stretch">
          <Pressable
            accessibilityRole="button"
            accessibilityLabel="Skip onboarding"
            onPress={completeOnboarding}
            className="rounded-full px-4 py-2"
          >
            <Text className="text-[14px] font-semibold text-faint">Skip</Text>
          </Pressable>

          <View className="flex-row items-center gap-2">
            {PAGES.map((item, index) => (
              <View
                key={item.eyebrow}
                className={`h-2 rounded-full ${
                  index === page ? "w-6 bg-accent" : "w-2 bg-line"
                }`}
              />
            ))}
          </View>

          <Pressable
            accessibilityRole="button"
            accessibilityLabel={isLastPage ? "Get started" : "Next"}
            onPress={goNext}
            className="items-center justify-center rounded-full bg-accent px-6 py-3"
          >
            <Text className="text-[14px] font-semibold text-white">
              {isLastPage ? "Get started" : "Next"}
            </Text>
          </Pressable>
        </View>
      </View>
    </View>
  );
}

export default OnboardingScreen;
